const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const output = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/collection-plan.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText, {exports:output});
const invoices = [{id:1,outstanding:1000},{id:2,outstanding:500},{id:3,outstanding:0}];
let plan=output.collectionPlan(invoices,[2,1],1200);
assert.equal(plan.allocations[0].invoice_id,1,'allocation follows invoice order, not ticking order');
assert.equal(plan.allocations[0].amount,1000);
assert.equal(plan.allocations[1].amount,200);
assert.equal(plan.allocations[1].remaining,300);
assert.equal(plan.unallocated,0);
plan=output.collectionPlan(invoices,[1],1200);assert.equal(plan.unallocated,200,'extra money is never silently discarded');
plan=output.collectionPlan(invoices,[2],500);assert.equal(plan.allocations[0].remaining,0,'full settlement');
plan=output.collectionPlan(invoices,[3],100);assert.equal(plan.unallocated,100,'paid invoices cannot absorb a payment');
plan=output.collectionPlan([{id:1,outstanding:.1},{id:2,outstanding:.2}],[1,2],.3);assert.equal(plan.unallocated,0,'cent arithmetic');
assert.equal(output.collectionPlan(invoices,[],100).unallocated,100);
assert.equal(output.collectionPlan(invoices,[1],NaN).allocations[0].amount,0);
console.log('11 customer collection allocation checks passed.');
